"""Prepares IRCC's French forms IMM 5710 and IMM 5707 for the site. Run again whenever IRCC publishes a new version.

Reads tools/ircc/imm5710f.pdf and tools/ircc/imm5707f.pdf (IRCC's files, unchanged) and writes:
- assets/formulaire/ircc-lists.js: IRCC's value lists (countries, statuses, languages, cities...) from the IMM 5710,
  used by the questionnaire, so the client's answers are already IRCC's codes;
- assets/ircc/imm5710f.js and assets/ircc/imm5707f.js: what /outil/mobilite-francophone/ needs to fill each form in
  the browser: the PDF itself, its decrypted XFA packets to rewrite, and the values to append an encrypted
  incremental update.

The PDFs are AES-128 encrypted with an empty user password (anyone can open them); the per-object keys written here
are derived from public data, they protect nothing secret.

Usage (needs pikepdf):  python3 -m venv /tmp/v && /tmp/v/bin/pip install pikepdf && /tmp/v/bin/python tools/ircc/prepare.py
"""
import base64
import hashlib
import json
import os
import unicodedata
import xml.etree.ElementTree as ET

import pikepdf

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
XFA_DATA = '{http://www.xfa.org/schema/xfa-data/1.0/}data'

# Each form: the XFA packets the fill rewrites (always 'datasets'; the IMM 5707 also needs 'form', where Acrobat keeps
# which blocks are shown, since its spouse/children blocks only change on a click).
FORMS = {
    'imm5710': {'packets': ['datasets']},
    'imm5707': {'packets': ['form', 'datasets']},
}

LISTS = ['PreferenceLanguage', 'GenderMel', 'CountryOfBirth', 'CountryOfCitizenship', 'Country', 'ImmigrationStatus',
         'CountryOfLastPermanentResident', 'MaritalStatus', 'MaritalStatusHistory', 'ContactLanguage',
         'AbleCommunicateEnglishOrFrench', 'CountryTravelDocument', 'ProvinceAbbrev', 'StateAbbrev', 'PhoneTypeTRV',
         'VisitPurposeOriginal', 'WorkPermitTypeInLand']
SORTED = {'CountryOfBirth', 'CountryOfCitizenship', 'Country', 'CountryOfLastPermanentResident', 'ContactLanguage',
          'CountryTravelDocument'}


def sort_key(label):
    return unicodedata.normalize('NFD', label).encode('ascii', 'ignore').decode().lower()


def items(node):
    out = []
    for e in node.iter():
        label = (e.text or '').strip()
        if e is not node and e.get('lic') and label:
            out.append([e.get('lic'), label])
    return out


def form_version(datasets):
    """IRCC's version string: IMM 5710 stores it in the data; IMM 5707 only in its file name date (see form packet)."""
    node = ET.fromstring(datasets).find(XFA_DATA + '/form1/Page1/FormVersion')
    return node.text if node is not None else None


def write_lists(datasets, version):
    lov = ET.fromstring(datasets).find('LOVFile/LOV')
    lists = {}
    for name in LISTS:
        values = items(lov.find(name + 'List'))
        if name in SORTED:
            values.sort(key=lambda v: sort_key(v[1]))
        lists[name] = values
    lists['City'] = {prov.get('lic'): sorted(items(prov), key=lambda v: sort_key(v[1])) for prov in lov.find('CityList')}
    with open(os.path.join(ROOT, 'assets/formulaire/ircc-lists.js'), 'w') as f:
        f.write('// Generated by tools/ircc/prepare.py from IRCC IMM 5710 (%s). Do not edit.\n' % version)
        f.write('window.IRCC_LISTS = ' + json.dumps(lists, ensure_ascii=False, separators=(',', ':')) + ';\n')
    return lists


def pack(form_id, spec):
    src = os.path.join(HERE, form_id + 'f.pdf')
    raw = open(src, 'rb').read()
    pdf = pikepdf.open(src)
    xfa = pdf.Root.AcroForm.XFA
    names = [str(xfa[i]) for i in range(0, len(xfa), 2)]
    key = pdf.encryption.encryption_key
    packets = {}
    for name in spec['packets']:
        obj = xfa[names.index(name) * 2 + 1]
        num, gen = obj.objgen
        packets[name] = {
            'num': num, 'gen': gen,
            'key': hashlib.md5(key + num.to_bytes(3, 'little') + gen.to_bytes(2, 'little') + b'sAlT').digest().hex(),
            'xml': obj.read_bytes().decode('utf-8'),
        }
    nums = sorted(p['num'] for p in packets.values())
    assert nums == list(range(nums[0], nums[0] + len(nums))), 'packets must be consecutive objects: %r' % nums
    datasets = packets['datasets']['xml']
    version = form_version(datasets)
    if version is None:
        form = xfa[names.index('form') * 2 + 1].read_bytes().decode('utf-8')
        version = ET.fromstring(form).find('{*}subform/{*}field[@name="FormNumber"]/{*}value/{*}text').text
    trailer = pdf.trailer
    out = {
        'id': form_id,
        'formVersion': version,
        'sha256': hashlib.sha256(raw).hexdigest(),
        'pdf': base64.b64encode(raw).decode(),
        'packets': packets,
        'size': int(trailer.Size),
        'prev': int(raw[raw.rindex(b'startxref') + 9:].split()[0]),
        'root': '%d %d R' % pdf.Root.objgen,
        'encrypt': '%d %d R' % trailer.Encrypt.objgen,
        'info': '%d %d R' % trailer.Info.objgen,
        'ids': [bytes(x).hex() for x in trailer.ID],
    }
    os.makedirs(os.path.join(ROOT, 'assets/ircc'), exist_ok=True)
    with open(os.path.join(ROOT, 'assets/ircc', form_id + 'f.js'), 'w') as f:
        f.write('// Generated by tools/ircc/prepare.py from IRCC %s (%s). Do not edit.\n' % (form_id.upper(), version))
        f.write('window.IRCC_FORMS = window.IRCC_FORMS || {};\n')
        f.write('window.IRCC_FORMS[%s] = ' % json.dumps(form_id) + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
    return datasets, version


def main():
    for form_id, spec in FORMS.items():
        datasets, version = pack(form_id, spec)
        print(form_id, version)
        if form_id == 'imm5710':
            lists = write_lists(datasets, version)
            print('  lists', {k: len(v) for k, v in lists.items()})


if __name__ == '__main__':
    main()
