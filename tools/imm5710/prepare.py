"""Prepares IRCC's IMM 5710 (French) for the site. Run again whenever IRCC publishes a new version of the form.

Reads tools/imm5710/imm5710f.pdf (IRCC's file, unchanged) and writes:
- assets/formulaire/ircc-lists.js: IRCC's value lists (countries, statuses, languages, cities...) used by the
  questionnaire, so the client's answers are already IRCC's codes;
- assets/imm5710/imm5710f.js: what /outil/imm5710/ needs to fill the form in the browser: the PDF itself,
  its decrypted XFA data template, and the values to append an encrypted incremental update.

The PDF is AES-128 encrypted with an empty user password (anyone can open it); the per-object key written here
is derived from public data, it protects nothing secret.

Usage (needs pikepdf):  python3 -m venv /tmp/v && /tmp/v/bin/pip install pikepdf && /tmp/v/bin/python tools/imm5710/prepare.py
"""
import base64
import hashlib
import json
import os
import unicodedata
import xml.etree.ElementTree as ET

import pikepdf

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(HERE, 'imm5710f.pdf')

LISTS = ['PreferenceLanguage', 'GenderMel', 'CountryOfBirth', 'CountryOfCitizenship', 'Country', 'ImmigrationStatus',
         'CountryOfLastPermanentResident', 'MaritalStatus', 'MaritalStatusHistory', 'ContactLanguage',
         'AbleCommunicateEnglishOrFrench', 'CountryTravelDocument', 'ProvinceAbbrev', 'StateAbbrev', 'PhoneTypeTRV',
         'VisitPurposeOriginal', 'WorkPermitTypeInLand']
SORTED = {'CountryOfBirth', 'CountryOfCitizenship', 'Country', 'CountryOfLastPermanentResident', 'ContactLanguage',
          'CountryTravelDocument'}


def sort_key(label):
    return unicodedata.normalize('NFD', label).encode('ascii', 'ignore').decode().lower()


def items(node):
    out = []
    for e in node.iter():
        label = (e.text or '').strip()
        if e is not node and e.get('lic') and label:
            out.append([e.get('lic'), label])
    return out


def main():
    raw = open(SRC, 'rb').read()
    pdf = pikepdf.open(SRC)
    xfa = pdf.Root.AcroForm.XFA
    names = [str(xfa[i]) for i in range(0, len(xfa), 2)]
    ds = xfa[names.index('datasets') * 2 + 1]
    datasets = ds.read_bytes().decode('utf-8')

    # Value lists.
    lov = ET.fromstring(datasets).find('LOVFile/LOV')
    lists = {}
    for name in LISTS:
        values = items(lov.find(name + 'List'))
        if name in SORTED:
            values.sort(key=lambda v: sort_key(v[1]))
        lists[name] = values
    lists['City'] = {prov.get('lic'): sorted(items(prov), key=lambda v: sort_key(v[1])) for prov in lov.find('CityList')}
    form_version = ET.fromstring(datasets).find('{http://www.xfa.org/schema/xfa-data/1.0/}data/form1/Page1/FormVersion').text
    with open(os.path.join(ROOT, 'assets/formulaire/ircc-lists.js'), 'w') as f:
        f.write('// Generated by tools/imm5710/prepare.py from IRCC IMM 5710 (%s). Do not edit.\n' % form_version)
        f.write('window.IRCC_LISTS = ' + json.dumps(lists, ensure_ascii=False, separators=(',', ':')) + ';\n')

    # Fill package for /outil/imm5710/.
    key = pdf.encryption.encryption_key
    num, gen = ds.objgen
    obj_key = hashlib.md5(key + num.to_bytes(3, 'little') + gen.to_bytes(2, 'little') + b'sAlT').digest()
    trailer = pdf.trailer
    pack = {
        'formVersion': form_version,
        'sha256': hashlib.sha256(raw).hexdigest(),
        'pdf': base64.b64encode(raw).decode(),
        'datasets': datasets,
        'num': num, 'gen': gen,
        'objKey': obj_key.hex(),
        'size': int(trailer.Size),
        'prev': int(raw[raw.rindex(b'startxref') + 9:].split()[0]),
        'root': '%d %d R' % pdf.Root.objgen,
        'encrypt': '%d %d R' % trailer.Encrypt.objgen,
        'info': '%d %d R' % trailer.Info.objgen,
        'ids': [bytes(x).hex() for x in trailer.ID],
    }
    os.makedirs(os.path.join(ROOT, 'assets/imm5710'), exist_ok=True)
    with open(os.path.join(ROOT, 'assets/imm5710/imm5710f.js'), 'w') as f:
        f.write('// Generated by tools/imm5710/prepare.py from IRCC IMM 5710 (%s). Do not edit.\n' % form_version)
        f.write('window.IMM5710 = ' + json.dumps(pack, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print('IMM 5710', form_version, '·', {k: len(v) for k, v in lists.items()})


if __name__ == '__main__':
    main()
